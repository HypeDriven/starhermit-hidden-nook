// Writes the play scripts that drive whole rounds through the real UI
// (tests/native/lesson.play, journey.play, practice.play) from the rules and
// content: for each requested object in wave order it presses the arrow
// that cycles the focus over the unfound objects (index order, starting
// before the first after each find) until the target is focused, then
// Enter. The practice round also taps a decoy, undoes it and asks for a
// hint. Run after a content change: node tools/gen-plays.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const R = require('../js/rules.js');
const C = require('../js/content.js');

/** Key steps that focus item `target` and select it; `focus` is the focused index before. */
function selectSteps(state, target, focus) {
  const idxs = R.legalActions(state).filter((a) => a.type === 'find').map((a) => a.index);
  let cur = idxs.indexOf(focus);
  const out = [];
  for (let guard = 0; guard < 64; guard++) {
    cur = (cur + 1 + idxs.length) % idxs.length;
    out.push('key ArrowRight 1', 'frames 5');
    if (idxs[cur] === target) break;
  }
  out.push('key Enter 1', 'frames 10');
  return out;
}
/** Plays every wave in order; `hintBefore` asks for a hint before the last find. Returns [steps, state]. */
function playAll(level, mode, { hintBeforeLast = false, decoyFirst = false } = {}) {
  let s = R.createSession(level, { mode });
  let focus = -1;
  const out = [];
  let id = 0;
  const apply = (cmd) => { const r = R.applyCommand(s, { ...cmd, id: 'g' + (id++) }); if (r.error) throw new Error(r.error); s = r.state; };
  if (decoyFirst) {
    const decoy = level.items.findIndex((it) => !it.requested);
    out.push('# a wrong tap (a decoy), then undo', ...selectSteps(s, decoy, focus));
    apply({ type: 'find', index: decoy });
    focus = decoy;
    out.push('key KeyU 1', 'frames 10');
    apply({ type: 'undo' });
  }
  const order = level.waves.flat();
  order.forEach((target, k) => {
    if (hintBeforeLast && k === order.length - 1) { out.push('# a hint', 'key KeyH 1', 'frames 10'); apply({ type: 'hint' }); }
    out.push(`# find ${level.items[target].name}`, ...selectSteps(s, target, focus));
    apply({ type: 'find', index: target });
    focus = target;
  });
  return [out, s];
}

const header = (lines) => lines.map((l) => '# ' + l).join('\n') + '\n';

// The lesson: Play on a fresh save starts it; the first arrow press is its look-around step.
{
  const lv = C.tutorialLevel();
  const [steps, s] = playAll(lv, 'learn', { hintBeforeLast: true });
  const total = R.scoreBreakdown(s).total;
  writeFileSync('tests/native/lesson.play', header([
    'The lesson end to end: Play on a fresh save opens its rules card, Begin, the',
    'countdown, then every requested object by the arrow keys and Enter (the',
    'first arrow is the look-around step), a hint before the last find; the',
    `results (total ${total}), the progress screen and the title with "Replay lesson".`,
    'Generated by tools/gen-plays.mjs.',
  ]) + ['until 300 Hidden Nook', 'frames 60', 'save title', 'click Play (starts with a quick lesson)', 'until 60 Interactive lesson', 'frames 10', 'save lesson-setup',
    'click =Begin', 'until 400 =Pause', 'frames 20', 'expect Lesson 1/5', 'save lesson-round', ...steps,
    'until 120 Nook cleared!', 'frames 30', `expect ${total}`, 'expect First Light', 'save lesson-results', 'click =Menu', 'until 60 Objects found all-time', 'frames 10',
    'save progress', 'click =Back to title', 'until 60 Replay lesson', 'frames 10', 'expect Play', ''].join('\n'));
}

